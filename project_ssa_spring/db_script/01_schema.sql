CREATE TABLE MEMBER (
    MEMBER_ID       VARCHAR2(50 CHAR) NOT NULL,
    NAME            VARCHAR2(50 CHAR) NOT NULL,
    DEPARTMENT      VARCHAR2(20 CHAR) NOT NULL,
    PASSWORD        VARCHAR2(100 CHAR) NOT NULL,
    STATUS          VARCHAR2(1 CHAR) DEFAULT '0' NOT NULL,
    FAIL_COUNT      NUMBER(10) DEFAULT 0 NOT NULL,
    PWD_CHG_DATE    DATE DEFAULT SYSDATE NOT NULL,
    LAST_LONG_DATE  DATE,
    REG_DATE        DATE DEFAULT SYSDATE NOT NULL,
    PHONE           VARCHAR2(100 CHAR),
    EMAIL           VARCHAR2(300 CHAR) NOT NULL,
    PICTURE         VARCHAR2(200 CHAR) DEFAULT 'noImage.jpg' NOT NULL,
    CONSTRAINT PK_MEMBER PRIMARY KEY (MEMBER_ID),
    CONSTRAINT CK_MEMBER_STATUS CHECK (STATUS IN ('0', '1', '2')),
    CONSTRAINT CK_MEMBER_FAIL_COUNT CHECK (FAIL_COUNT >= 0)
);
COMMENT ON TABLE MEMBER IS '사용자 계정';

CREATE TABLE MEMBER_ROLE (
    ROLE_ID     NUMBER(10) NOT NULL,
    ROLE_CODE   VARCHAR2(30 CHAR) DEFAULT 'ROLE_GUEST' NOT NULL,
    MEMBER_ID   VARCHAR2(50 CHAR) NOT NULL,
    CONSTRAINT PK_MEMBER_ROLE PRIMARY KEY (ROLE_ID),
    CONSTRAINT UQ_MEMBER_ROLE UNIQUE (MEMBER_ID, ROLE_CODE),
    CONSTRAINT FK_MEMBER_ROLE_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (MEMBER_ID),
    CONSTRAINT CK_MEMBER_ROLE_CODE CHECK (ROLE_CODE IN ('ROLE_ADMIN', 'ROLE_USER', 'ROLE_GUEST'))
);
COMMENT ON TABLE MEMBER_ROLE IS '사용자 권한';

CREATE TABLE MEMBER_LOG (
