CREATE TABLE WORKFLOW (
    APPROVAL_ID    NUMBER(10) NOT NULL,
    APP_STATUS     VARCHAR2(1 CHAR) DEFAULT '0' NOT NULL,
    REJECT_REASON  VARCHAR2(1000 CHAR),
    ADMIN_SIGN     VARCHAR2(1 CHAR) DEFAULT 'N' NOT NULL,
    REQUEST_DATE   DATE DEFAULT SYSDATE NOT NULL,
    COMPLETE_DATE  DATE,
    DRAFTER_ID     VARCHAR2(50 CHAR) NOT NULL,
    APPROVER_ID    VARCHAR2(50 CHAR) NOT NULL,
    REPORT_ID      NUMBER(10) NOT NULL,
    CONSTRAINT PK_WORKFLOW PRIMARY KEY (APPROVAL_ID),
    CONSTRAINT FK_WORKFLOW_DRAFTER FOREIGN KEY (DRAFTER_ID) REFERENCES MEMBER (MEMBER_ID),
    CONSTRAINT FK_WORKFLOW_APPROVER FOREIGN KEY (APPROVER_ID) REFERENCES MEMBER (MEMBER_ID),
    CONSTRAINT FK_WORKFLOW_REPORT FOREIGN KEY (REPORT_ID) REFERENCES PATROL_REPORT (REPORT_ID),
    CONSTRAINT CK_WORKFLOW_STATUS CHECK (APP_STATUS IN ('0', '1', '2')),
    CONSTRAINT CK_WORKFLOW_SIGN CHECK (ADMIN_SIGN IN ('Y', 'N'))
);
COMMENT ON TABLE WORKFLOW IS '보고서 결재 이력';

