CREATE TABLE PATROL_REPORT (
    REPORT_ID           NUMBER(10) NOT NULL,
    REPORT_DATE         DATE NOT NULL,
    TOTAL_FLIGHT_TIME   NUMBER(12,2) DEFAULT 0 NOT NULL,
    TOTAL_DETECT_COUNT  NUMBER(10) DEFAULT 0 NOT NULL,
    COMPLETION_RATE     NUMBER(6,2) DEFAULT 0 NOT NULL,
    CONFIRM_STATUS      VARCHAR2(1 CHAR) DEFAULT '0' NOT NULL,
    PATROL_DATE         DATE NOT NULL,
    MOD_DATE            TIMESTAMP,
    MEMBER_ID           VARCHAR2(50 CHAR) NOT NULL,
    ACTION_TAKEN        VARCHAR2(4000 BYTE),
    REMARK              VARCHAR2(4000 BYTE),
