    CONSTRAINT CK_PATROL_REPORT_COUNT CHECK (TOTAL_DETECT_COUNT >= 0),
    CONSTRAINT CK_PATROL_REPORT_RATE CHECK (COMPLETION_RATE BETWEEN 0 AND 100),
    CONSTRAINT CK_PATROL_REPORT_CONFIRM CHECK (CONFIRM_STATUS IN ('0', '1', '2'))
